<?php
// Generates csrc/src/sort_net.h: AVX2 bitonic sorting networks for the quicksort's leaves (csrc/src/sort.c).
//
//   php tools/gen-sort-net.php > csrc/src/sort_net.h
//
// One function per (key width, register count R): qs_net<W>_<R>(a, n) sorts n <= R * L keys (L = 256 / W lanes),
// padding with the largest key. Key slot i lives in register i % R, lane i / R ("column-major"), so the many
// short-distance steps of the network compare whole registers (no shuffles) and only distances >= R permute lanes.
// The network is the bitonic sort with a flip: for each block size s, slot i (bit s/2 clear) is compared with
// i ^ (s - 1), then with i ^ d for d = s/4 .. 1 (bit d clear); every compare-exchange puts the smaller key in the
// lower slot, so no direction masks are needed. The sorted slots are transposed back to memory order at the end.
// The code is straight-line over named registers so the compiler can keep them in registers.

// [key width, registers, kind]: i = signed integers (min/max through a compare), d = doubles without NaNs
// (min_pd/max_pd; -0.0 and +0.0 compare equal, so sort.c restores the zeros' signs afterwards)
$configs = [[64, 4, 'i'], [64, 8, 'i'], [64, 16, 'i'], [32, 8, 'i'], [32, 16, 'i'], [64, 4, 'd'], [64, 8, 'd'], [64, 16, 'd']];

echo "/* GENERATED by tools/gen-sort-net.php -- do not edit. AVX2 bitonic sorting networks for sort.c's quicksort leaves. */\n";
foreach ($configs as [$w, $r, $kind]) {
    echo net($w, $r, $kind), "\n";
}

function net(int $w, int $R, string $kind): string
{
    $L = intdiv(256, $w);
    $N = $R * $L;
    $T = $kind === 'd' ? 'double' : ($w === 64 ? 'qs_i64' : 'qs_i32');
    $max = $kind === 'd' ? 'INFINITY' : ($w === 64 ? 'INT64_MAX' : 'INT32_MAX');
    $name = $kind === 'd' ? "qs_netd_$R" : "qs_net{$w}_$R";
    $o = [];
    $o[] = "/* sorts n <= $N " . ($kind === 'd' ? 'doubles' : "int$w keys") . ": $R registers x $L lanes */";
    $o[] = "__attribute__((target(\"avx2\"))) static void $name($T *a, int64_t n)";
    $o[] = '{';
    $o[] = "    TSR_NOINIT $T buf[$N] __attribute__((aligned(32)));";
    $o[] = "    memcpy(buf, a, (size_t)n * sizeof($T));";
    $o[] = "    for (int64_t i = n; i < $N; i++) buf[i] = $max;";
    for ($j = 0; $j < $R; $j++) {
        $o[] = "    __m256i r$j = _mm256_load_si256((const __m256i *)(buf + " . ($j * $L) . '));';
    }
    for ($s = 2; $s <= $N; $s *= 2) {
        stage($o, $w, $R, $L, $s - 1, intdiv($s, 2), $kind);         // flip
        for ($d = intdiv($s, 4); $d >= 1; $d = intdiv($d, 2)) {
            stage($o, $w, $R, $L, $d, $d, $kind);                      // half-cleaners
        }
    }
    // slot i = lane * R + reg: lane l of registers g .. g+B-1 is the run buf[l * R + g ..]
    if ($w === 64) {
        for ($g = 0; $g < $R; $g += 4) {
            [$a, $b, $c, $d] = ["r$g", 'r' . ($g + 1), 'r' . ($g + 2), 'r' . ($g + 3)];
            $o[] = '    {';
            $o[] = "        const __m256i t0 = _mm256_unpacklo_epi64($a, $b), t1 = _mm256_unpackhi_epi64($a, $b);";
            $o[] = "        const __m256i t2 = _mm256_unpacklo_epi64($c, $d), t3 = _mm256_unpackhi_epi64($c, $d);";
            $o[] = "        _mm256_store_si256((__m256i *)(buf + " . (0 * $R + $g) . '), _mm256_permute2x128_si256(t0, t2, 0x20));';
            $o[] = "        _mm256_store_si256((__m256i *)(buf + " . (1 * $R + $g) . '), _mm256_permute2x128_si256(t1, t3, 0x20));';
            $o[] = "        _mm256_store_si256((__m256i *)(buf + " . (2 * $R + $g) . '), _mm256_permute2x128_si256(t0, t2, 0x31));';
            $o[] = "        _mm256_store_si256((__m256i *)(buf + " . (3 * $R + $g) . '), _mm256_permute2x128_si256(t1, t3, 0x31));';
            $o[] = '    }';
        }
    } else {
        for ($g = 0; $g < $R; $g += 8) {
            $x = [];
            for ($k = 0; $k < 8; $k++) $x[] = 'r' . ($g + $k);
            $o[] = '    {';
            for ($k = 0; $k < 8; $k += 2) {
                $o[] = "        const __m256i t$k = _mm256_unpacklo_epi32({$x[$k]}, {$x[$k + 1]}), t" . ($k + 1) . " = _mm256_unpackhi_epi32({$x[$k]}, {$x[$k + 1]});";
            }
            $o[] = '        const __m256i u0 = _mm256_unpacklo_epi64(t0, t2), u1 = _mm256_unpackhi_epi64(t0, t2);';
            $o[] = '        const __m256i u2 = _mm256_unpacklo_epi64(t1, t3), u3 = _mm256_unpackhi_epi64(t1, t3);';
            $o[] = '        const __m256i u4 = _mm256_unpacklo_epi64(t4, t6), u5 = _mm256_unpackhi_epi64(t4, t6);';
            $o[] = '        const __m256i u6 = _mm256_unpacklo_epi64(t5, t7), u7 = _mm256_unpackhi_epi64(t5, t7);';
            foreach ([0, 1, 2, 3] as $l) {
                $o[] = "        _mm256_store_si256((__m256i *)(buf + " . ($l * $R + $g) . "), _mm256_permute2x128_si256(u$l, u" . ($l + 4) . ', 0x20));';
                $o[] = "        _mm256_store_si256((__m256i *)(buf + " . (($l + 4) * $R + $g) . "), _mm256_permute2x128_si256(u$l, u" . ($l + 4) . ', 0x31));';
            }
            $o[] = '    }';
        }
    }
    $o[] = "    memcpy(a, buf, (size_t)n * sizeof($T));";
    $o[] = '}';
    return implode("\n", $o) . "\n";
}

/* one network step: slot i (bit b clear) against slot i ^ x, smaller key to slot i */
function stage(array &$o, int $w, int $R, int $L, int $x, int $b, string $kind): void
{
    $xr = $x % $R;
    $xl = intdiv($x, $R);
    if ($xl === 0) {                                      // registers r and r ^ xr, every lane alike
        for ($r = 0; $r < $R; $r++) {
            if (($r & $b) !== 0) continue;
            $q = $r ^ $xr;
            $o[] = '    { ' . minmax($w, "r$r", "r$q", $kind) . " r$r = mn; r$q = mx; }";
        }
        return;
    }
    $upper = upperMask($w, $L, intdiv($b, $R));           // lanes holding the upper slot of their pair
    for ($r = 0; $r < $R; $r++) {
        $q = $r ^ $xr;
        if ($q < $r) continue;
        if ($q === $r) {                                  // within one register
            $o[] = '    { const __m256i p = ' . perm($w, "r$r", $xl) . '; ' . minmax($w, "r$r", 'p', $kind)
                . " r$r = _mm256_blend_epi32(mn, mx, $upper); }";
        } else {                                          // register r against register q with lanes permuted
            $o[] = '    { const __m256i p = ' . perm($w, "r$q", $xl) . '; ' . minmax($w, "r$r", 'p', $kind)
                . " r$r = _mm256_blend_epi32(mn, mx, $upper); const __m256i t = _mm256_blend_epi32(mx, mn, $upper); r$q = "
                . perm($w, 't', $xl) . '; }';
        }
    }
}

function minmax(int $w, string $a, string $b, string $kind): string
{
    if ($kind === 'd') {
        return "const __m256d x_ = _mm256_castsi256_pd($a), y_ = _mm256_castsi256_pd($b); "
            . 'const __m256i mn = _mm256_castpd_si256(_mm256_min_pd(x_, y_)), mx = _mm256_castpd_si256(_mm256_max_pd(x_, y_));';
    }
    if ($w === 32) {
        return "const __m256i mn = _mm256_min_epi32($a, $b), mx = _mm256_max_epi32($a, $b);";
    }
    return "const __m256i g = _mm256_cmpgt_epi64($a, $b); const __m256i mn = _mm256_blendv_epi8($a, $b, g), mx = _mm256_blendv_epi8($b, $a, g);";
}

/* lane l takes lane l ^ xl */
function perm(int $w, string $v, int $xl): string
{
    if ($w === 64) {
        $imm = 0;
        for ($l = 0; $l < 4; $l++) $imm |= ($l ^ $xl) << (2 * $l);
        return sprintf('_mm256_permute4x64_epi64(%s, 0x%02X)', $v, $imm);
    }
    $in = function (string $e, int $x): string {
        $imm = 0;
        for ($l = 0; $l < 4; $l++) $imm |= ($l ^ $x) << (2 * $l);
        return sprintf('_mm256_shuffle_epi32(%s, 0x%02X)', $e, $imm);
    };
    if ($xl < 4) return $in($v, $xl);
    $swapped = "_mm256_permute4x64_epi64($v, 0x4E)";
    return $xl === 4 ? $swapped : $in($swapped, $xl ^ 4);
}

/* _mm256_blend_epi32 immediate selecting the lanes with bit bl set */
function upperMask(int $w, int $L, int $bl): string
{
    $imm = 0;
    for ($l = 0; $l < $L; $l++) {
        if (($l & $bl) === 0) continue;
        $imm |= $w === 64 ? (3 << (2 * $l)) : (1 << $l);
    }
    return sprintf('0x%02X', $imm);
}
