 * Run the NumPy/SciPy parity fixtures (tests/fixtures/parity/*.json) against one backend and record the
 * outcome per function in tools/parity/results.json (read by tools/parity/report.py).
 *
 *   php -d ffi.enable=1 tools/parity/run-tests.php --backend=ffi [--module=special] [--only=gammainc,jv] [-v]
 *   php -d extension=tessero tools/parity/run-tests.php --backend=ext
 *   ... --fixtures=<file.json> --no-record     # one fixture file; do not update results.json
 *   ... --preload=DIR/Stats.php                # façades generated with gen-facades.php --out=DIR
 *
 * Element-wise modules (`blocks`, generated by fixtures.py): every block is checked twice: once with arrays (the element loop, broadcasting, float64) and once with
 * PHP scalars on a sample of rows (the scalar path). A value passes when both are NaN, both are the same
 * infinity, or |got - want| <= atol + rtol |want| (defaults: rtol 1e-13, atol 0; per-function overrides in
 * the spec's `tol:`). Call-based modules (`calls`, generated by fixtures_np.py) replay each recorded call with
 * its keyword arguments as PHP named arguments and compare the result's kind (int/float/bool), shape and values
 * (default rtol 1e-12; NumPy's summation order is replicated, so most results are exact). Exit status 1 when
 * anything fails.
 */

