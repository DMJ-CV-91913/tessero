function dec(mixed $v): ?float
{
    return match ($v) {
        'nan' => NAN, 'inf' => INF, '-inf' => -INF, 'undef' => null, default => (float) $v,
    };
}

function camelName(string $s): string
{
    $parts = explode('_', $s);
    $out = array_shift($parts);
    foreach ($parts as $p) {
        $out .= $p === '' ? '_' : ucfirst($p);   /* gen-facades.php camel(): lambda_ stays lambda_ */
    }

    return $out;
}

/** @return array{bool, float} ok, relative error (0 when exact) */
function close(float $got, float $want, float $rtol, float $atol): array
{
    if (is_nan($want)) {
        return [is_nan($got), is_nan($got) ? 0.0 : INF];
    }
    if (is_infinite($want)) {
        return [$got === $want, $got === $want ? 0.0 : INF];
    }
    if (is_nan($got) || is_infinite($got)) {
        return [false, INF];
    }
    $err = abs($got - $want);
    $rel = $want != 0.0 ? $err / abs($want) : $err;

    return [$err <= $atol + $rtol * abs($want), $rel];
}

